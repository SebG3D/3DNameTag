#!/usr/bin/env python3
"""Flatten PrusaSlicer system presets (printer + print + filament) into one
self-contained .ini that `prusa-slicer --load` accepts.

The CLI can only use system presets that are installed in a GUI datadir; a
flat file in the repo is reproducible on the Pi instead. A config exported from
the PrusaSlicer GUI (File > Export > Export Config) can replace the output.

  python3 tools/make_profile.py            # 0.4 nozzle -> slicer/profiles/coreone_040.ini
  python3 tools/make_profile.py --printer "Prusa CORE One 0.25 nozzle" \
      --print "0.15mm SPEED @COREONE 0.25" -o slicer/profiles/coreone_025.ini
"""
import argparse
import re
from pathlib import Path

BUNDLE = Path("/usr/share/PrusaSlicer/profiles/PrusaResearch.ini")
OUT = Path(__file__).resolve().parents[1] / "slicer" / "profiles" / "coreone_040.ini"

# Booth overrides on top of the system presets.
OVERRIDES = {
    "binary_gcode": "0",          # plain G-code: we post-process it (T lines, checks)
    "gcode_label_objects": "firmware",
    "complete_objects": "0",
    # Colour change with a wipe tower: PrusaSlicer builds a tower only for a
    # tool change, so the printer is set up as two tools on one nozzle (XL-style
    # multi-tool, no MMU ramming/parking). The plate 3MF puts the text on tool 2;
    # the tool change is a plain M600 at the tower, then the tower purges the
    # new colour. slicer.py strips the T0/T1 lines PrusaSlicer always emits.
    # Tower position comes from the 3MF (PrusaSlicer 2.9 ignores wipe_tower_x/y).
    "single_extruder_multi_material": "0",
    "toolchange_gcode": "{if previous_extruder >= 0}M600 ; booth: text colour{endif}",
    "wipe_tower": "1",
    "wipe_tower_width": "12",
    "wipe_tower_brim_width": "2",
    "wiping_volumes_use_custom_matrix": "1",
    "wiping_volumes_matrix": "0,15,15,0",           # mm3 purged on the tower
    "filament_minimal_purge_on_wipe_tower": "10",
    "filament_multitool_ramming": "0",
    "ooze_prevention": "0",
    # Higher Z-hop: tiny PETG text curls up, and at 350 mm/s a 0.15 mm hop
    # caught it and shifted the layer (test 2026-11-12, 2nd text layer).
    "retract_lift": "0.4",
}
# Keep the bed hot after a plate: the next plate starts without the long
# bed heat-up (firmware safety timer still switches heaters off when idle).
END_GCODE_DROP = r"M140 S0 ; turn off heatbed\n"


def parse(path: Path) -> dict[str, dict[str, str]]:
    sections, cur = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if m := re.match(r"^\[(\w+):(.+)\]\s*$", line):
            cur = sections.setdefault(f"{m[1]}:{m[2]}", {})
        elif cur is not None and (m := re.match(r"^([A-Za-z0-9_]+)\s*=\s?(.*)$", line)):
            cur[m[1]] = m[2]
    return sections


def resolve(sections, kind: str, name: str, seen=()) -> dict[str, str]:
    key = f"{kind}:{name}"
    if key not in sections:
        raise SystemExit(f"preset not found: [{key}]")
    if key in seen:
        raise SystemExit(f"inheritance loop at {key}")
    own = sections[key]
    out = {}
    for parent in filter(None, (p.strip() for p in own.get("inherits", "").split(";"))):
        out.update(resolve(sections, kind, parent, seen + (key,)))
    out.update(own)
    out.pop("inherits", None)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--printer", default="Prusa CORE One 0.4 nozzle")
    ap.add_argument("--print", dest="print_", default="0.20mm BALANCED @COREONE 0.4")
    ap.add_argument("--filament", default="Prusament PLA @COREONE")
    ap.add_argument("-o", "--out", type=Path, default=OUT)
    a = ap.parse_args()
    s = parse(BUNDLE)
    cfg = {}
    for kind, name in (("printer", a.printer), ("print", a.print_), ("filament", a.filament)):
        cfg.update(resolve(s, kind, name))
    cfg.update(OVERRIDES)
    cfg["nozzle_diameter"] = f"{cfg['nozzle_diameter']},{cfg['nozzle_diameter']}"   # two tools, same nozzle
    if END_GCODE_DROP not in cfg["end_gcode"]:
        raise SystemExit("end_gcode: 'M140 S0 ; turn off heatbed' not found - check the preset")
    cfg["end_gcode"] = cfg["end_gcode"].replace(END_GCODE_DROP, "")
    # PrusaSlicer checks these against the preset names used in the G-code header
    cfg["printer_settings_id"] = a.printer
    cfg["print_settings_id"] = a.print_
    cfg["filament_settings_id"] = a.filament
    a.out.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# generated by tools/make_profile.py from {BUNDLE.name}\n"
              f"# printer: {a.printer}\n# print: {a.print_}\n# filament: {a.filament}\n")
    a.out.write_text(header + "".join(f"{k} = {v}\n" for k, v in sorted(cfg.items())))
    print(f"{a.out}: {len(cfg)} keys, layer_height={cfg.get('layer_height')}, "
          f"first_layer_height={cfg.get('first_layer_height')}, bed_shape={cfg.get('bed_shape')}")


if __name__ == "__main__":
    main()
